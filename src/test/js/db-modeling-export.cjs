const test = require("node:test");
const assert = require("node:assert/strict");
const { toSql, toSvg, columnType } = require("../../main/resources/static/js/db-modeling-export.js");
const column = (name, type, options = {}) => ({ name, type, pk: false, nullable: true, ...options });
const model = {
    tables: [
        { name: "order", comment: "고객's 주문", columns: [column("id", "bigint", { pk: true, increment: true }), column("active", "boolean", { nullable: false, defaultValue: "true" }), column("token", "uuid"), column("label", "varchar(60)", { unique: true, defaultValue: "'O''Reilly'" }), column("created_at", "timestamp(3)", { defaultValue: "`now()`" })] },
        { name: "line", columns: [column("order_id", "bigint", { pk: true }), column("line_id", "int", { pk: true }), column("price", "decimal(12,2)")] }
    ],
    refs: [{ fromTable: "line", fromColumn: "order_id", toTable: "order", toColumn: "id" }]
};

test("PostgreSQL DDL preserves modeled attributes and creates FKs after all tables", () => {
    const sql = toSql(model, "postgresql");
    assert.match(sql, /CREATE TABLE "order"/);
    assert.match(sql, /"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
    assert.match(sql, /"active" BOOLEAN NOT NULL DEFAULT TRUE/);
    assert.match(sql, /"token" UUID/);
    assert.match(sql, /DEFAULT 'O''Reilly' UNIQUE/);
    assert.match(sql, /TIMESTAMP\(3\) DEFAULT CURRENT_TIMESTAMP/);
    assert.match(sql, /PRIMARY KEY \("order_id", "line_id"\)/);
    assert(sql.indexOf("ALTER TABLE") > sql.lastIndexOf("CREATE TABLE"));
    assert.match(sql, /REFERENCES "order" \("id"\)/);
});

test("MySQL/MariaDB uses quoted names, AUTO_INCREMENT and InnoDB", () => {
    const sql = toSql(model, "mysql");
    assert.match(sql, /`id` BIGINT AUTO_INCREMENT NOT NULL/);
    assert.match(sql, /`token` CHAR\(36\)/);
    assert.match(sql, /ENGINE=InnoDB COMMENT='고객''s 주문'/);
});

test("SQL Server and Oracle use native identity, boolean and UUID types", () => {
    const server = toSql(model, "sqlserver"), oracle = toSql(model, "oracle");
    assert.match(server, /\[id\] BIGINT IDENTITY\(1,1\) NOT NULL/);
    assert.match(server, /\[active\] BIT NOT NULL DEFAULT 1/);
    assert.match(server, /\[token\] UNIQUEIDENTIFIER/);
    assert.match(server, /DATETIME2\(3\)/);
    assert.match(oracle, /"id" NUMBER\(19\) GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
    assert.match(oracle, /"active" NUMBER\(1\) NOT NULL DEFAULT 1/);
    assert.match(oracle, /"token" RAW\(16\)/);
    assert.match(oracle, /VARCHAR2\(60 CHAR\)/);
});

test("SQL identifiers and comments cannot break out of their context", () => {
    const dangerous = { tables: [{ name: 'x"y', comment: "hello\nDROP TABLE nope", columns: [column('a"b', "int")] }], refs: [] };
    assert.match(toSql(dangerous, "postgresql"), /CREATE TABLE "x""y"/);
    assert.match(toSql(dangerous, "postgresql"), /"a""b" INT/);
    assert(!toSql(dangerous, "postgresql").includes("\nDROP TABLE"));
    dangerous.tables[0].name = "x]y";
    assert.match(toSql(dangerous, "sqlserver"), /CREATE TABLE \[x]]y]/);
});

test("JSON defaults and validation use the target database syntax", () => {
    const json = { tables: [{ name: "payload", columns: [column("body", "json", { defaultValue: "'{}'" }), column("title", "nvarchar(60)", { defaultValue: "N'한글'" })] }], refs: [] };
    assert.match(toSql(json, "mysql"), /JSON DEFAULT \('\{\}'\)/);
    assert.match(toSql(json, "sqlserver"), /NVARCHAR\(MAX\) DEFAULT N'\{\}' CHECK \(ISJSON\(\[body\]\) = 1\)/);
    assert.match(toSql(json, "sqlserver"), /DEFAULT N'한글'/);
    assert.match(toSql(json, "oracle"), /CLOB DEFAULT '\{\}' CHECK \("body" IS JSON\)/);
    assert.match(toSql(json, "postgresql"), /DEFAULT '한글'/);
});

test("Composite references preserve every participating column", () => {
    const composite = structuredClone(model);
    composite.tables.push({ name: "detail", columns: [column("order_id", "bigint"), column("line_id", "int")] });
    composite.refs.push({ fromTable: "detail", fromColumn: "order_id", fromColumns: ["order_id", "line_id"], toTable: "line", toColumn: "order_id", toColumns: ["order_id", "line_id"] });
    assert.match(toSql(composite, "postgresql"), /FOREIGN KEY \("order_id", "line_id"\) REFERENCES "line" \("order_id", "line_id"\)/);
});

test("Unsupported definitions fail explicitly instead of producing incomplete SQL", () => {
    assert.throws(() => toSql(model, "invalid"));
    assert.throws(() => toSql({ tables: [], refs: [] }, "postgresql"));
    assert.throws(() => columnType("geometry", "postgresql"));
    assert.throws(() => toSql(model, "postgresql", "Test", "CREATE INDEX idx ON line(price);"));
    assert.throws(() => toSql(model, "mysql", "Test", "CREATE TABLE a (id int CHECK(id>0));"));
    assert.throws(() => toSql(model, "mysql", "Test", "Ref: line.order_id > order.id [delete: cascade]"));
    const invalid = structuredClone(model);
    invalid.tables[0].columns[1].defaultValue = "unsupported_function()";
    assert.throws(() => toSql(invalid, "oracle"));
});

test("SVG is standalone vector output with all tables, relations and saved positions", () => {
    const drawing = toSvg(model, { order: { x: 10, y: 20 }, line: { x: 2010, y: 820 } }, "한글 <ERD>");
    assert(drawing.width > 2200 && drawing.height > 900);
    assert.match(drawing.svg, /<title>한글 &lt;ERD&gt;<\/title>/);
    assert.match(drawing.svg, /marker-end="url\(#arrow\)"/);
    assert.match(drawing.svg, /<text[^>]*>line<\/text>/);
    assert(!drawing.svg.includes("foreignObject"));
    const hostile = structuredClone(model);
    hostile.tables[0].name = '<script>alert(1)</script>';
    assert(!toSvg(hostile).svg.includes("<script>"));
});
